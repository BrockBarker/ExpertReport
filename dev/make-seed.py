#!/usr/bin/env python3
"""Turn the checked data files in ../data into app/js/seed.js, which the app loads on first run."""
import base64, json, os, subprocess
here = os.path.dirname(os.path.abspath(__file__)); root = os.path.dirname(here)
sp = json.load(open(os.path.join(root, 'data', 'species-factors-louisiana.json')))
ratings = {
 'id': 'ratings',
 'lists': [{
   'id': 'usda-la',
   'name': 'Louisiana species factors (USDA Forest Service, i-Tree)',
   'short': 'USDA Forest Service species factors for Louisiana (Nowak 2024, Understanding i-Tree, Appendix 7, Table 15)',
   'citation': sp['source']['citation'], 'doi': sp['source']['doi'],
   'about': sp['source']['what_the_source_says'],
   'items': [{'sci': s['scientific'], 'common': s['common'], 'pct': round(s['factor'] * 100)} for s in sp['species']]}],
 'custom': []}
for s, r in zip(sp['species'], ratings['lists'][0]['items']):
    assert abs(r['pct'] / 100 - s['factor']) < 1e-9, s
def sheet(fid, name):
    d = json.load(open(os.path.join(root, 'data', 'price-sheets', name)))
    items = []
    for i in d['items']:
        dims = ' '.join(x for x in [i.get('container', ''), i.get('height_x_spread', '') or i.get('height', '')] if x)
        items.append({'cat': i['category'], 'variety': i['variety'], 'dims': dims, 'caliper': i.get('caliper_in', ''),
                      'price': i['price_usd'], 'ltd': bool(i.get('limited')), 'comments': i.get('comments', '')})
    return {'id': fid, 'supplier': d['supplier'], 'address': d.get('address', ''), 'title': d['title'], 'date': d.get('date', ''),
            'basis': d['price_basis'], 'source': d.get('source_file', ''), 'notes': d.get('notes', ''), 'items': items, 'seeded': True}
foret = sheet('gerald-foret-2025-03', 'gerald-foret-2025-03.json'); foret['date'] = 'March - April 2025'
sheets = [foret, sheet('wilkinson-field-grown', 'wilkinson-field-grown.json')]
logo = os.path.join(root, 'app', 'img', 'logo.png')
out = subprocess.run(['sips', '-g', 'pixelWidth', '-g', 'pixelHeight', logo], capture_output=True, text=True).stdout.split()
w, h = int(out[out.index('pixelWidth:') + 1]), int(out[out.index('pixelHeight:') + 1])
seed = {'version': 1, 'ratings': ratings, 'sheets': sheets,
        'logo': {'type': 'png', 'w': w, 'h': h, 'data': base64.b64encode(open(logo, 'rb').read()).decode()}}
open(os.path.join(root, 'app', 'js', 'seed.js'), 'w').write('/* Generated by dev/make-seed.py from the files in data/. Do not edit by hand. */\nwindow.SEED = ' + json.dumps(seed, ensure_ascii=False) + ';\n')
print('seed.js:', len(ratings['lists'][0]['items']), 'species;', [(s['supplier'], len(s['items'])) for s in sheets], '; logo', w, 'x', h)
